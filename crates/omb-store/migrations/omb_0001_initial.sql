CREATE TABLE openmybot.control_tokens (
    token_id uuid NOT NULL PRIMARY KEY,
    token_sha256 bytea NOT NULL,
    daemon_pid integer NOT NULL,
    engine_pin text NOT NULL,
    omb_version text NOT NULL,
    pg_system_identifier text NOT NULL,
    pg_timeline_id integer NOT NULL,
    restore_detected boolean NOT NULL,
    created_at timestamptz NOT NULL,
    last_heartbeat_at timestamptz NOT NULL,
    revoked_at timestamptz,
    revoke_reason text,
    CONSTRAINT control_tokens_check_1 CHECK (engine_pin ~ '^[0-9a-f]{40}$'),
    CONSTRAINT control_tokens_check_2 CHECK (octet_length(token_sha256)=32),
    CONSTRAINT control_tokens_check_3 CHECK (octet_length(pg_system_identifier)<=128),
    CONSTRAINT control_tokens_check_4 CHECK (revoke_reason IN ('daemon_stop','daemon_restart'))
);

CREATE TABLE openmybot.channel_bindings (
    binding_id uuid NOT NULL PRIMARY KEY,
    binding_kind text NOT NULL,
    channel_kind text NOT NULL,
    source_key text NOT NULL,
    sender_key text,
    chat_key text,
    credential_envelope text,
    workspace_dir text,
    thread_id text,
    thread_generation integer NOT NULL DEFAULT 0,
    revision bigint NOT NULL DEFAULT 0,
    granted_generation bigint,
    run_deadline_seconds integer,
    pairing_code_hash bytea,
    pairing_expires_at timestamptz,
    status text NOT NULL,
    status_reason text,
    created_at timestamptz NOT NULL,
    activated_at timestamptz,
    suspended_at timestamptz,
    reconfirmed_at timestamptz,
    ended_at timestamptz,
    CONSTRAINT channel_bindings_check_1 CHECK (run_deadline_seconds BETWEEN 1 AND 86400),
    CONSTRAINT channel_bindings_check_2 CHECK (binding_kind <> 'receiver' OR (channel_kind IN ('telegram','feishu') AND credential_envelope IS NOT NULL AND sender_key IS NULL AND chat_key IS NULL AND workspace_dir IS NULL AND thread_id IS NULL AND status <> 'pending')),
    CONSTRAINT channel_bindings_check_3 CHECK (binding_kind <> 'sender' OR (channel_kind IN ('telegram','feishu') AND (status <> 'pending' OR (pairing_code_hash IS NOT NULL AND pairing_expires_at IS NOT NULL AND workspace_dir IS NOT NULL AND thread_id IS NOT NULL AND granted_generation IS NOT NULL AND sender_key IS NULL)) AND (status NOT IN ('active','suspended') OR (sender_key IS NOT NULL AND chat_key IS NOT NULL AND workspace_dir IS NOT NULL AND thread_id IS NOT NULL AND granted_generation IS NOT NULL AND pairing_code_hash IS NULL)))),
    CONSTRAINT channel_bindings_check_4 CHECK (binding_kind <> 'host' OR (channel_kind='host' AND source_key='crabcode' AND sender_key IS NOT NULL AND sender_key='host:crabcode' AND workspace_dir IS NOT NULL AND granted_generation IS NOT NULL AND status <> 'pending')),
    CONSTRAINT channel_bindings_check_5 CHECK (octet_length(source_key)<=128),
    CONSTRAINT channel_bindings_check_6 CHECK (octet_length(sender_key)<=128),
    CONSTRAINT channel_bindings_check_7 CHECK (octet_length(chat_key)<=128),
    CONSTRAINT channel_bindings_check_8 CHECK (octet_length(thread_id)<=128),
    CONSTRAINT channel_bindings_check_9 CHECK (octet_length(pairing_code_hash)=32),
    CONSTRAINT channel_bindings_check_10 CHECK (binding_kind IN ('receiver','sender','host')),
    CONSTRAINT channel_bindings_check_11 CHECK (channel_kind IN ('telegram','feishu','host')),
    CONSTRAINT channel_bindings_check_12 CHECK (status IN ('pending','active','suspended','revoked','expired')),
    CONSTRAINT channel_bindings_check_13 CHECK (status_reason IN ('superseded','pairing_expired','owner_revoked','receiver_replaced','restore_detected','credential_rejected','webhook_conflict','grant_stale'))
);

CREATE TABLE openmybot.channel_events (
    record_id uuid NOT NULL PRIMARY KEY,
    record_kind text NOT NULL,
    channel_kind text NOT NULL,
    source_key text NOT NULL,
    event_key text NOT NULL,
    event_type text,
    occurred_at timestamptz,
    accepted_at timestamptz NOT NULL,
    fingerprint bytea,
    sender_key text,
    chat_key text,
    binding_id uuid REFERENCES openmybot.channel_bindings(binding_id),
    disposition text NOT NULL,
    command text,
    text text,
    text_sha256 bytea,
    run_id text,
    thread_id text,
    dispatch_status text,
    dispatch_attempts integer NOT NULL DEFAULT 0,
    next_dispatch_at timestamptz,
    dispatched_at timestamptz,
    terminal_kind text,
    terminal_at timestamptz,
    gap_started_at timestamptz,
    gap_ended_at timestamptz,
    gap_reason text,
    content_cleared_at timestamptz,
    CONSTRAINT channel_events_check_1 CHECK ((record_kind='gap')=(disposition='gap')),
    CONSTRAINT channel_events_check_2 CHECK (record_kind <> 'gap' OR (gap_started_at IS NOT NULL AND gap_reason IS NOT NULL)),
    CONSTRAINT channel_events_check_3 CHECK (disposition <> 'accepted_message' OR (text IS NOT NULL AND text_sha256 IS NOT NULL AND run_id IS NOT NULL AND thread_id IS NOT NULL AND binding_id IS NOT NULL AND dispatch_status IS NOT NULL)),
    CONSTRAINT channel_events_check_4 CHECK (disposition NOT IN ('dropped_unbound','dropped_not_private') OR (fingerprint IS NULL AND text IS NULL AND sender_key IS NULL AND chat_key IS NULL)),
    CONSTRAINT channel_events_check_5 CHECK (disposition NOT IN ('pairing_succeeded','pairing_failed','pairing_locked') OR (sender_key IS NOT NULL AND fingerprint IS NOT NULL)),
    CONSTRAINT channel_events_check_6 CHECK (disposition='accepted_message' OR text IS NULL),
    CONSTRAINT channel_events_check_7 CHECK (octet_length(source_key)<=128),
    CONSTRAINT channel_events_check_8 CHECK (octet_length(event_key)<=128),
    CONSTRAINT channel_events_check_9 CHECK (octet_length(fingerprint)=32),
    CONSTRAINT channel_events_check_10 CHECK (octet_length(sender_key)<=128),
    CONSTRAINT channel_events_check_11 CHECK (octet_length(chat_key)<=128),
    CONSTRAINT channel_events_check_12 CHECK (octet_length(text_sha256)=32),
    CONSTRAINT channel_events_check_13 CHECK (octet_length(run_id)<=128),
    CONSTRAINT channel_events_check_14 CHECK (octet_length(thread_id)<=128),
    CONSTRAINT channel_events_check_15 CHECK (record_kind IN ('event','gap')),
    CONSTRAINT channel_events_check_16 CHECK (channel_kind IN ('telegram','feishu','host')),
    CONSTRAINT channel_events_check_17 CHECK (disposition IN ('accepted_message','control_command','pairing_succeeded','pairing_failed','pairing_locked','dropped_unbound','dropped_not_private','dropped_inactive','rejected_outside_window','rejected_too_long','rejected_unsupported','rejected_malformed','rejected_queue_full','gap')),
    CONSTRAINT channel_events_check_18 CHECK (command IN ('help','start','status','cancel','pair','unknown')),
    CONSTRAINT channel_events_check_19 CHECK (dispatch_status IN ('pending','dispatched','conflict','expired','cancelled')),
    CONSTRAINT channel_events_check_20 CHECK (terminal_kind IN ('succeeded','failed','cancelled','reconciliation_required')),
    CONSTRAINT channel_events_check_21 CHECK (gap_reason IN ('daemon_down','daemon_suspended','connect_failed','stream_broken','receiver_suspended'))
);

CREATE TABLE openmybot.host_driver_sessions (
    record_id uuid NOT NULL PRIMARY KEY,
    record_kind text NOT NULL,
    run_id text NOT NULL,
    binding_id uuid NOT NULL REFERENCES openmybot.channel_bindings(binding_id),
    host_kind text,
    host_version text,
    args_sha256 bytea,
    native_session_id text,
    resumed_from text,
    resumable boolean,
    workspace_dir text,
    child_pid integer,
    pgid integer,
    started_at timestamptz,
    init_at timestamptz,
    last_event_at timestamptz,
    last_event_seq bigint,
    output_bytes bigint,
    ended_at timestamptz,
    exit_code integer,
    exit_signal integer,
    end_reason text,
    stop_outcome text,
    stop_confirmed_at timestamptz,
    result_summary text,
    artifact_paths text[],
    stderr_tail text,
    content_cleared_at timestamptz,
    permission_id text,
    native_request_id text,
    tool_name text,
    input_summary text,
    input_sha256 bytea,
    requested_at timestamptz,
    expires_at timestamptz,
    decision text,
    decided_via text,
    decided_at timestamptz,
    decided_by_token uuid REFERENCES openmybot.control_tokens(token_id),
    answered_at timestamptz,
    CONSTRAINT host_driver_sessions_check_1 CHECK (record_kind <> 'session' OR (host_kind IS NOT NULL AND started_at IS NOT NULL AND workspace_dir IS NOT NULL AND num_nonnulls(permission_id,native_request_id,tool_name,input_summary,input_sha256,requested_at,expires_at,decision,decided_via,decided_at,decided_by_token,answered_at)=0)),
    CONSTRAINT host_driver_sessions_check_2 CHECK (record_kind <> 'permission' OR (permission_id IS NOT NULL AND tool_name IS NOT NULL AND requested_at IS NOT NULL AND expires_at IS NOT NULL AND num_nonnulls(host_kind,host_version,args_sha256,native_session_id,resumed_from,resumable,workspace_dir,child_pid,pgid,started_at,init_at,last_event_at,last_event_seq,output_bytes,ended_at,exit_code,exit_signal,end_reason,stop_outcome,stop_confirmed_at,result_summary,artifact_paths,stderr_tail)=0)),
    CONSTRAINT host_driver_sessions_check_3 CHECK (octet_length(run_id)<=128),
    CONSTRAINT host_driver_sessions_check_4 CHECK (octet_length(args_sha256)=32),
    CONSTRAINT host_driver_sessions_check_5 CHECK (octet_length(native_session_id)<=128),
    CONSTRAINT host_driver_sessions_check_6 CHECK (octet_length(resumed_from)<=128),
    CONSTRAINT host_driver_sessions_check_7 CHECK (octet_length(permission_id)<=128),
    CONSTRAINT host_driver_sessions_check_8 CHECK (octet_length(native_request_id)<=128),
    CONSTRAINT host_driver_sessions_check_9 CHECK (octet_length(input_sha256)=32),
    CONSTRAINT host_driver_sessions_check_10 CHECK (record_kind IN ('session','permission')),
    CONSTRAINT host_driver_sessions_check_11 CHECK (host_kind IN ('crabcode')),
    CONSTRAINT host_driver_sessions_check_12 CHECK (end_reason IN ('result_success','result_error','stop_requested','output_limit','line_limit','stalled','protocol_error','child_exited','spawn_failed','version_rejected','init_timeout','resume_failed')),
    CONSTRAINT host_driver_sessions_check_13 CHECK (stop_outcome IN ('confirmed','unknown')),
    CONSTRAINT host_driver_sessions_check_14 CHECK (decision IN ('allow','deny')),
    CONSTRAINT host_driver_sessions_check_15 CHECK (decided_via IN ('readonly_rule','cli','timeout','run_stopped'))
);

CREATE TABLE openmybot.deliveries (
    delivery_id uuid NOT NULL PRIMARY KEY,
    binding_id uuid NOT NULL REFERENCES openmybot.channel_bindings(binding_id),
    channel_kind text NOT NULL,
    chat_key text NOT NULL,
    kind text NOT NULL,
    idempotency_key text NOT NULL,
    body text,
    status text NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz,
    first_attempt_at timestamptz,
    last_error_code text,
    platform_message_id text,
    created_at timestamptz NOT NULL,
    finished_at timestamptz,
    content_cleared_at timestamptz,
    CONSTRAINT deliveries_check_1 CHECK (status NOT IN ('sent','failed','unknown') OR finished_at IS NOT NULL),
    CONSTRAINT deliveries_check_2 CHECK (octet_length(chat_key)<=128),
    CONSTRAINT deliveries_check_3 CHECK (octet_length(idempotency_key)<=128),
    CONSTRAINT deliveries_check_4 CHECK (octet_length(platform_message_id)<=128),
    CONSTRAINT deliveries_check_5 CHECK (channel_kind IN ('telegram','feishu')),
    CONSTRAINT deliveries_check_6 CHECK (kind IN ('run_result','permission_notice','control_reply','pairing_reply','reject_reply','expiry_notice')),
    CONSTRAINT deliveries_check_7 CHECK (status IN ('pending','sending','sent','failed','unknown'))
);

CREATE UNIQUE INDEX control_token_digest ON openmybot.control_tokens(token_sha256);
CREATE UNIQUE INDEX control_token_live ON openmybot.control_tokens((1)) WHERE revoked_at IS NULL;
CREATE UNIQUE INDEX binding_live_kind ON openmybot.channel_bindings(binding_kind,channel_kind) WHERE status IN ('pending','active','suspended');
CREATE UNIQUE INDEX event_identity ON openmybot.channel_events(channel_kind,source_key,event_key);
CREATE UNIQUE INDEX event_run ON openmybot.channel_events(run_id) WHERE run_id IS NOT NULL;
CREATE UNIQUE INDEX session_run ON openmybot.host_driver_sessions(run_id) WHERE record_kind='session';
CREATE UNIQUE INDEX permission_identity ON openmybot.host_driver_sessions(permission_id) WHERE record_kind='permission';
CREATE UNIQUE INDEX permission_native_request ON openmybot.host_driver_sessions(run_id,native_request_id) WHERE record_kind='permission';
CREATE UNIQUE INDEX delivery_idempotency ON openmybot.deliveries(idempotency_key);
